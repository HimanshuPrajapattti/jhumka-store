CREATE OR REPLACE FUNCTION public.format_inr(amount bigint)
RETURNS text
LANGUAGE plpgsql
IMMUTABLE
SET search_path = pg_catalog, public, pg_temp
AS $$
DECLARE
  digits text := abs(amount)::text;
  formatted text;
BEGIN
  IF length(digits) <= 3 THEN
    formatted := digits;
  ELSE
    formatted := right(digits, 3);
    digits := left(digits, length(digits) - 3);
    WHILE length(digits) > 2 LOOP
      formatted := right(digits, 2) || ',' || formatted;
      digits := left(digits, length(digits) - 2);
    END LOOP;
    formatted := digits || ',' || formatted;
  END IF;
  RETURN (CASE WHEN amount < 0 THEN '-₹' ELSE '₹' END) || formatted;
END;
$$;

CREATE OR REPLACE FUNCTION public.place_store_order(
  p_ref text,
  p_name text,
  p_phone text,
  p_address text,
  p_note text,
  p_items jsonb
)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = pg_catalog, public, pg_temp
AS $$
DECLARE
  requested record;
  product_row public.products%ROWTYPE;
  line jsonb;
  order_id bigint;
  total integer := 0;
  lines jsonb := '[]'::jsonb;
  order_message text;
  item_number integer := 0;
BEGIN
  IF jsonb_typeof(p_items) <> 'array'
     OR jsonb_array_length(p_items) = 0
     OR jsonb_array_length(p_items) > 50 THEN
    RETURN jsonb_build_object('error', 'invalid_cart');
  END IF;

  IF EXISTS (
    SELECT 1
    FROM jsonb_array_elements(p_items) AS entries(item)
    WHERE jsonb_typeof(item) <> 'object'
       OR item->>'id' !~ '^[1-9][0-9]*$'
       OR item->>'qty' !~ '^[1-9][0-9]*$'
  ) THEN
    RETURN jsonb_build_object('error', 'invalid_cart');
  END IF;

  FOR requested IN
    SELECT (item->>'id')::bigint AS product_id,
           sum((item->>'qty')::integer)::integer AS qty
    FROM jsonb_array_elements(p_items) AS entries(item)
    GROUP BY (item->>'id')::bigint
    ORDER BY (item->>'id')::bigint
  LOOP
    IF requested.qty > 20 THEN
      RETURN jsonb_build_object('error', 'invalid_cart');
    END IF;

    SELECT * INTO product_row
    FROM public.products
    WHERE id = requested.product_id
    FOR UPDATE;

    IF NOT FOUND THEN
      RETURN jsonb_build_object('error', 'product_unavailable');
    END IF;
    IF product_row.stock < requested.qty THEN
      RETURN jsonb_build_object(
        'error', 'out_of_stock',
        'name', product_row.name,
        'available', product_row.stock
      );
    END IF;

    total := total + product_row.price * requested.qty;
    lines := lines || jsonb_build_array(jsonb_build_object(
      'product_id', product_row.id,
      'name', product_row.name,
      'price', product_row.price,
      'qty', requested.qty
    ));
  END LOOP;

  order_message := '🛍️ *New Order — AVRANI*' || E'\nRef: ' || p_ref
    || E'\n\n*Items:*';
  FOR line IN SELECT value FROM jsonb_array_elements(lines)
  LOOP
    item_number := item_number + 1;
    order_message := order_message || E'\n' || item_number || '. '
      || line->>'name'
      || E'\n   ' || public.format_inr((line->>'price')::bigint)
      || ' × ' || line->>'qty'
      || ' = ' || public.format_inr(
        (line->>'price')::bigint * (line->>'qty')::bigint
      );
  END LOOP;

  order_message := order_message || E'\n\n*Total: '
    || public.format_inr(total) || E'*\n\n*Customer:*\nName: '
    || p_name || E'\nPhone: ' || p_phone || E'\nAddress: ' || p_address;
  IF length(btrim(p_note)) > 0 THEN
    order_message := order_message || E'\nNote: ' || btrim(p_note);
  END IF;
  order_message := order_message || E'\n\n— ordered via AVRANI website';

  INSERT INTO public.orders (
    ref, customer_name, phone, address, note, subtotal, total, status, message
  )
  VALUES (
    p_ref, p_name, p_phone, p_address, btrim(p_note), total, total, 'pending',
    order_message
  )
  RETURNING id INTO order_id;

  FOR line IN SELECT value FROM jsonb_array_elements(lines)
  LOOP
    INSERT INTO public.order_items (
      order_id, product_id, product_name, price, qty
    )
    VALUES (
      order_id,
      (line->>'product_id')::bigint,
      line->>'name',
      (line->>'price')::integer,
      (line->>'qty')::integer
    );

    UPDATE public.products
    SET stock = stock - (line->>'qty')::integer
    WHERE id = (line->>'product_id')::bigint;
  END LOOP;

  RETURN jsonb_build_object(
    'id', order_id,
    'ref', p_ref,
    'total', total,
    'message', order_message
  );
END;
$$;

